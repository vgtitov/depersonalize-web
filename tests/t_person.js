// Один человек в разных формах получает одну метку.
const assert = require("assert");
const { depersonalize, restore } = require("../engine.js");
let r = depersonalize("Иван Петрович Сидоров пришёл. Позвонили Сидорову Ивану, потом Сидорова Ивана.", []);
assert.strictEqual(r.text, "[ЧЕЛОВЕК_1] пришёл. Позвонили [ЧЕЛОВЕК_1], потом [ЧЕЛОВЕК_1].");
assert.strictEqual(r.counts["ЧЕЛОВЕК"], 1);
// одинокая фамилия, ранее названная полностью (в том числе до полного имени)
r = depersonalize("Директор сказала Сидорову, что отчёт готов. Иван Петрович Сидоров согласен.", []);
assert.strictEqual(r.text, "Директор сказала [ЧЕЛОВЕК_1], что отчёт готов. [ЧЕЛОВЕК_1] согласен.");
// инициалы и женская форма
r = depersonalize("Козлова Мария пришла. Иванов И. И. ушёл. Козловой Марии передали.", []);
assert.strictEqual(r.text, "[ЧЕЛОВЕК_1] пришла. [ЧЕЛОВЕК_2] ушёл. [ЧЕЛОВЕК_1] передали.");
// разные люди остаются разными
r = depersonalize("Иван Сидоров и Пётр Сидоров", []);
assert.strictEqual(r.text, "[ЧЕЛОВЕК_1] и [ЧЕЛОВЕК_2]");
// имя без фамилии: Анна Сергеевна в разных падежах
r = depersonalize("Анна Сергеевна звонила. Передали Анне Сергеевне.", []);
assert.strictEqual(r.text, "[ЧЕЛОВЕК_1] звонила. Передали [ЧЕЛОВЕК_1].");
// слово, не названное человеком выше, одиноким не заменяется
assert.strictEqual(depersonalize("Сидорову передали", []).text, "Сидорову передали");
// возврат даёт самую полную из встреченных форм
r = depersonalize("Сидорову Ивану сказали. Позже Иван Петрович Сидоров ответил.", []);
assert.strictEqual(restore(r.text, r.map), "Иван Петрович Сидоров сказали. Позже Иван Петрович Сидоров ответил.");
console.log("один человек, одна метка: ok");
