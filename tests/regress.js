// Прежние случаи ревью должны остаться исправленными.
const assert = require("assert");
const { depersonalize } = require("../engine.js");
const eq = (t, d, want) => assert.strictEqual(depersonalize(t, d).text, want, t);
eq("ИВАНОВ ИВАН ИВАНОВИЧ", [], "[ЧЕЛОВЕК_1]");
eq("Иванов И. И. и И.И. Петров", [], "[ЧЕЛОВЕК_1] и [ЧЕЛОВЕК_2]");
eq("Почта: info@пример.рф", [], "Почта: [EMAIL_1]");
eq("Позвонил Иван Иванович", [], "Позвонил [ЧЕЛОВЕК_1]");
eq("Позвонил Иван Петров", [], "Позвонил [ЧЕЛОВЕК_1]");
eq("Передать Анне Сергеевне.", ["x"], "Передать [ЧЕЛОВЕК_1].");
eq("Для Павла Сергеевича.", ["x"], "Для [ЧЕЛОВЕК_1].");
eq("Звоните +375 29 123-45-67 или 8 017 200-00-00 до 18:00", [], "Звоните [ТЕЛЕФОН_1] или [ТЕЛЕФОН_2] до 18:00");
eq("УНП 123456789, ИНН 7707083893", [], "УНП [УНП_1], ИНН [ИНН_1]");
eq("карта 4111 1111 1111 1111", [], "карта [КАРТА_1]");
eq("Образец [EMAIL_1]; адрес a@example.com", [], "Образец [EMAIL_1]; адрес [EMAIL_2]");
console.log("регрессия: ok");
